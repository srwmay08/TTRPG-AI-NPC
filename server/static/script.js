let messageQueue = [];

// Extrapolates Actions (asterisks) and Speech (quotes) from a raw message
function formatDiscordMessage(msg) {
    let lines = [];
    const actionRegex = /\*([^*]+)\*/g;
    let actionMatch;
    let speechText = msg;
    
    // Parse actions and format them with natural asterisks
    while ((actionMatch = actionRegex.exec(msg)) !== null) {
        lines.push(`*${actionMatch[1].trim()}*`);
        speechText = speechText.replace(actionMatch[0], ''); 
    }
    
    // Parse speech (raw text without "Speech:" prefix)
    speechText = speechText.trim();
    if (speechText) {
        // Strip outer quotes if they exist to prevent double quoting
        speechText = speechText.replace(/^"([^"]+)"$/, '$1').trim(); 
        lines.push(speechText);
    }
    
    return lines.join('\n');
}

function parseLogToQueue(rawLog) {
    const regex = /\[.*?\] \[Scriptly\] (.*?)\n(.*?)(?=\n\[|$)/gs;
    let match;
    const queue = [];

    while ((match = regex.exec(rawLog)) !== null) {
        const discordName = match[1].trim();
        const rawMessage = match[2].trim();
        
        if (!rawMessage) continue;

        const characterName = discordToPcMap[discordName] || discordName;
        
        queue.push({
            discordName: discordName,
            characterName: characterName,
            rawMessage: rawMessage
        });
    }
    return queue;
}

document.addEventListener('DOMContentLoaded', () => {
    const stepBtn = document.getElementById('step-discord-log-btn');
    const pasteArea = document.getElementById('discord-log-paste');
    const liveMessagesDiv = document.getElementById('live-discord-messages');

    if (stepBtn && pasteArea) {
        stepBtn.addEventListener('click', () => {
            
            // 1. Initialize Queue if empty
            if (messageQueue.length === 0 && pasteArea.value.trim() !== '') {
                messageQueue = parseLogToQueue(pasteArea.value);
                if (messageQueue.length > 0) liveMessagesDiv.innerHTML = '';
            }

            // 2. Process Next Message
            if (messageQueue.length > 0) {
                const nextMsg = messageQueue.shift();
                const parsedContent = formatDiscordMessage(nextMsg.rawMessage);
                
                // Print to visual feed
                const msgElem = document.createElement('p');
                msgElem.style.margin = '4px 0';
                msgElem.innerHTML = `<strong style="color: #4da6ff;">[${nextMsg.discordName} / ${nextMsg.characterName}]</strong> ${nextMsg.rawMessage}`;
                liveMessagesDiv.appendChild(msgElem);
                liveMessagesDiv.scrollTop = liveMessagesDiv.scrollHeight;

                // Route parsed text to the appropriate dynamic inbox generated by app.js
                let targetTextAreaId = 'gm-utterance'; 
                
                if (nextMsg.characterName !== "DM") {
                    const allChars = window.AppState ? window.AppState.getAllCharacters() : [];
                    const pc = allChars.find(c => c.name === nextMsg.characterName && (c.character_type === 'PC' || c.character_type === 'Player Character'));
                    
                    if (pc) {
                        // If PC isn't active, activate them and render the box
                        if (window.AppState && !window.AppState.hasActivePc(pc._id)) {
                            window.AppState.addActivePc(pc._id);
                            if (window.PCRenderers) {
                                const activePcs = window.AppState.getAllCharacters().filter(c => c.character_type === 'PC');
                                PCRenderers.renderPcListUI(activePcs);
                            }
                            if (window.App && window.App.renderPartyInboxUI) {
                                window.App.renderPartyInboxUI(); 
                            }
                        }
                        targetTextAreaId = `pc-utterance-${pc._id}`;
                    }
                }

                // Append to the correct text area
                const dynamicUtteranceArea = document.getElementById(targetTextAreaId) || document.getElementById('player-utterance');
                if (dynamicUtteranceArea) {
                    dynamicUtteranceArea.value += (dynamicUtteranceArea.value ? "\n" : "") + parsedContent;
                    
                    // Flash effect to confirm input registration
                    const originalBg = dynamicUtteranceArea.style.backgroundColor;
                    dynamicUtteranceArea.style.backgroundColor = '#2c4a2c'; 
                    setTimeout(() => { dynamicUtteranceArea.style.backgroundColor = originalBg; }, 300);
                }

            } else {
                console.log("End of log reached or no text pasted.");
                const endElem = document.createElement('p');
                endElem.style.color = '#ff9999';
                endElem.style.marginTop = '10px';
                endElem.textContent = "--- End of pasted log or waiting for new messages ---";
                liveMessagesDiv.appendChild(endElem);
                liveMessagesDiv.scrollTop = liveMessagesDiv.scrollHeight;
            }
        });
    }
});